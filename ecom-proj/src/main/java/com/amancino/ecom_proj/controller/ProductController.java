package com.amancino.ecom_proj.controller;

import com.amancino.ecom_proj.model.Product;
import com.amancino.ecom_proj.service.ProductService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.servlet.http.HttpServletRequest;
import org.apache.coyote.Response;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ProblemDetail;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.util.ArrayList;
import java.util.List;

@Tag(
        name = "Products",
        description = "Endpoints for managing products"
)
@ApiResponse(
        responseCode = "401",
        description = "Missing or invalid credentials",
        content = @Content(
                mediaType = MediaType.APPLICATION_PROBLEM_JSON_VALUE,
                schema = @Schema(implementation = ProblemDetail.class)
        )
)
@RestController
@CrossOrigin
@RequestMapping("/api")
public class ProductController {

    @Autowired
    private ProductService service;

    @Operation(
            summary = "List all products",
            description = "Returns every product, including its image metadata."
    )
    @ApiResponse(responseCode = "200", description = "List of products (empty if there are none)")
    @GetMapping("/products")
    public ResponseEntity<List<Product>> getAllProducts() {
        return new ResponseEntity<>(service.getAllProducts(), HttpStatus.OK);
    }

    @Operation(
            summary = "Get a product by id"
    )
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Product found"),
            @ApiResponse(
                    responseCode = "404",
                    description = "No product exists with this id",
                    content = @Content(
                            mediaType = MediaType.APPLICATION_PROBLEM_JSON_VALUE,
                            schema = @Schema(implementation = ProblemDetail.class)
                    )
            )
    })
    @GetMapping("/products/{id}")
    public ResponseEntity<Product> getProductById(@PathVariable int id) {
        Product product = service.getProductById(id);
        return new ResponseEntity<>(product, HttpStatus.OK);
    }

    @Operation(
            summary = "Create a product",
            description = "Multipart request: a JSON part named 'product' and a file part named 'imageFile'. "
                    + "The id is generated by the server and must not be sent."
    )
    @ApiResponses({
            @ApiResponse(responseCode = "201", description = "Product created"),
            @ApiResponse(
                    responseCode = "400",
                    description = "Malformed JSON, invalid field value, or missing part",
                    content = @Content(
                            mediaType = MediaType.APPLICATION_PROBLEM_JSON_VALUE,
                            schema = @Schema(implementation = ProblemDetail.class)
                    )
            ),
            @ApiResponse(
                    responseCode = "500",
                    description = "The uploaded image could not be read",
                    content = @Content(
                            mediaType = MediaType.APPLICATION_PROBLEM_JSON_VALUE,
                            schema = @Schema(implementation = ProblemDetail.class)
                    )
            )
    })
    @PostMapping("/product")
    public ResponseEntity<Product> addProduct(
            @RequestPart Product product,
            @RequestPart MultipartFile imageFile
    ) {
        Product returnedProduct = service.addProduct(product, imageFile);
        return new ResponseEntity<>(returnedProduct, HttpStatus.CREATED);
    }

    @Operation(
            summary = "Get the image of a product",
            description = "Returns the raw image bytes, with the content type that was stored at upload time."
    )
    @ApiResponses({
            @ApiResponse(
                    responseCode = "200",
                    description = "Image bytes",
                    content = @Content(
                            mediaType = "image/*",
                            schema = @Schema(type = "string", format = "binary")
                    )
            ),
            @ApiResponse(
                    responseCode = "404",
                    description = "No product exists with this id",
                    content = @Content(
                            mediaType = MediaType.APPLICATION_PROBLEM_JSON_VALUE,
                            schema = @Schema(implementation = ProblemDetail.class)
                    )
            )
    })
    @GetMapping("product/{productId}/image")
    public ResponseEntity<byte[]> getImageByProductId(@PathVariable int productId) {
        Product product = service.getProductById(productId);
        byte[] imageFile = product.getImageData();

        return ResponseEntity.ok()
                .contentType(MediaType.valueOf(product.getImageType()))
                .body(imageFile);
    }

    @Operation(
            summary = "Replace a product",
            description = "Replaces all fields of an existing product, including its image. "
                    + "Multipart request: a JSON part named 'product' and a file part named 'imageFile'. "
                    + "The id in the URL is the one that is used, even if the JSON contains a different one."
    )
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Product updated"),
            @ApiResponse(
                    responseCode = "400",
                    description = "Malformed JSON, invalid field value, or missing part",
                    content = @Content(
                            mediaType = MediaType.APPLICATION_PROBLEM_JSON_VALUE,
                            schema = @Schema(implementation = ProblemDetail.class)
                    )
            ),
            @ApiResponse(
                    responseCode = "404",
                    description = "No product exists with this id",
                    content = @Content(
                            mediaType = MediaType.APPLICATION_PROBLEM_JSON_VALUE,
                            schema = @Schema(implementation = ProblemDetail.class)
                    )
            ),
            @ApiResponse(
                    responseCode = "500",
                    description = "The uploaded image could not be read",
                    content = @Content(
                            mediaType = MediaType.APPLICATION_PROBLEM_JSON_VALUE,
                            schema = @Schema(implementation = ProblemDetail.class)
                    )
            )
    })
    @PutMapping("/product/{id}/")
    public ResponseEntity<Product> updateProduct(
            @PathVariable int id,
            @RequestPart Product product,
            @RequestPart MultipartFile imageFile
    ) {
        Product returnedProduct = service.updateProduct(id, product, imageFile);

        return ResponseEntity.ok()
                .body(returnedProduct);
    }

    @Operation(
            summary = "Delete a product"
    )
    @ApiResponses({
            @ApiResponse(responseCode = "204", description = "Product deleted"),
            @ApiResponse(
                    responseCode = "404",
                    description = "No product exists with this id",
                    content = @Content(
                            mediaType = MediaType.APPLICATION_PROBLEM_JSON_VALUE,
                            schema = @Schema(implementation = ProblemDetail.class)
                    )
            )
    })
    @DeleteMapping("/product/{id}/")
    public ResponseEntity<Void> deleteProduct(@PathVariable int id) {
        service.deleteProduct(id);

        return ResponseEntity.noContent()
                .build();
    }

    @Operation(
            summary = "Search products",
            description = "Case-insensitive search: returns products whose name, description, brand "
                    + "or category contains the keyword."
    )
    @ApiResponse(responseCode = "200", description = "Matching products (empty if none match)")
    @GetMapping("products/search")
    public ResponseEntity<List<Product>> searchProduct(@RequestParam String keyword) {
        List<Product> products = service.searchProducts(keyword);

        return ResponseEntity.ok(products);
    }
}
